"""figScienceProvision: publication export of pipeline report 026.

Reads the report's backing CSVs (code/figures/026_landscape.csv and
026_exposure.csv, written by code/student_success/science_provision.py)
and renders a clean publication figure into code/figures/paper0:
vector PDF, 300-DPI PNG preview, TeX snippet with the canonical caption,
and a consolidated data CSV. Analysis stays in the pipeline; this module
only restyles its published aggregates (csv module + numpy, no pandas).
"""
import csv
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

HERE = Path(__file__).resolve().parent
FIG_SRC = HERE.parent / "figures"
FIG_DIR = HERE.parent / "figures" / "paper0"

BLUE, ORANGE, GRAY = "#2a78d6", "#eb6834", "#c3c2b7"
INK, INK_MUTED, GRID = "#0b0b0b", "#898781", "#e1e0d9"

ORDER = ["Biology", "Geometry", "Chemistry", "AP mathematics",
         "Physics", "AP science", "Calculus"]
CORE = {"Biology", "Geometry", "Chemistry", "Physics"}

plt.rcParams.update({"pdf.fonttype": 42, "font.family": "sans-serif",
                     "text.color": INK})


def _read(name: str) -> dict[str, dict[str, str]]:
    """CSV rows keyed by subject."""
    with open(FIG_SRC / name, newline="", encoding="utf-8") as f:
        return {r["subject"]: r for r in csv.DictReader(f)}


def figure() -> str:
    land = _read("026_landscape.csv")
    expo = _read("026_exposure.csv")

    nat = np.array([float(land[s]["pct_zero_national"]) for s in ORDER])
    snd = np.array([float(land[s]["pct_zero_utsa_schools"]) for s in ORDER])
    stu = np.array([float(expo[s]["pct_students_zero_school"]) for s in ORDER])
    n_nat = int(land[ORDER[0]]["n_national"])
    n_snd = int(land[ORDER[0]]["n_utsa_schools"])
    n_stu = int(expo[ORDER[0]]["n_students"])

    x = np.arange(len(ORDER))
    w = 0.27
    fig, ax = plt.subplots(figsize=(13, 6.2))
    ax.bar(x - w, nat, w * 0.9, color=GRAY,
           label=f"all CRDC high schools (N={n_nat:,})", zorder=3)
    ax.bar(x, snd, w * 0.9, color=BLUE,
           label=f"UT San Antonio sending schools (N={n_snd:,})", zorder=3)
    ax.bar(x + w, stu, w * 0.9, color=ORANGE,
           label=f"UT San Antonio entrants, student-weighted "
                 f"(N={n_stu:,})", zorder=3)
    for i in range(len(ORDER)):
        for dx, v, col in ((-w, nat[i], INK_MUTED), (0, snd[i], BLUE),
                           (w, stu[i], ORANGE)):
            ax.text(i + dx, v + 0.8, f"{v:.0f}", ha="center", fontsize=12,
                    color=col, fontweight="bold")
    ax.set_xticks(x)
    ax.set_xticklabels([s.replace(" ", "\n") for s in ORDER], fontsize=15)
    ax.set_ylabel("share with zero enrollment in subject (%)", fontsize=17)
    ax.tick_params(axis="y", labelsize=15, color=INK_MUTED)
    ax.tick_params(axis="x", color=INK_MUTED)
    ax.grid(axis="y", color=GRID, linewidth=0.6, zorder=0)
    ax.set_axisbelow(True)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(INK_MUTED)
    ax.legend(loc="upper left", fontsize=13, frameon=False)
    fig.tight_layout()

    FIG_DIR.mkdir(parents=True, exist_ok=True)
    pdf = FIG_DIR / "figScienceProvision.pdf"
    fig.savefig(pdf, bbox_inches="tight")
    fig.savefig(FIG_DIR / "figScienceProvision.png", dpi=300,
                bbox_inches="tight")
    plt.close(fig)

    with open(FIG_DIR / "figScienceProvision_data.csv", "w", newline="",
              encoding="utf-8") as f:
        out = csv.writer(f)
        out.writerow(["subject", "pct_zero_national",
                      "pct_zero_utsa_schools", "pct_students_zero_school",
                      "n_national", "n_utsa_schools", "n_students"])
        for i, s in enumerate(ORDER):
            out.writerow([s, nat[i], snd[i], stu[i], n_nat, n_snd, n_stu])

    core = [snd[i] for i, s in enumerate(ORDER) if s in CORE]
    adv = {s: snd[i] for i, s in enumerate(ORDER) if s not in CORE}
    (FIG_DIR / "figScienceProvision.tex").write_text(
        "% Canonical caption for figScienceProvision.pdf\n"
        "% Generated by: code/paper0/science_figure.py from the report-026\n"
        "% aggregates (code/figures/026_landscape.csv, 026_exposure.csv)\n"
        "% Regenerate: python code/paper0/science_figure.py\n"
        "\\begin{figure}[tbp]\n"
        "  \\centering\n"
        "  \\includegraphics[width=\\textwidth]{figScienceProvision.pdf}\n"
        "  \\caption{Course-provision deserts by subject: share of high\n"
        "    schools enrolling no student in each subject, CRDC 2017--18.\n"
        f"    Gray: all {n_nat:,} CRDC high schools. Blue: the {n_snd:,}\n"
        "    schools that sent entrants to UT San Antonio. Orange: UT San\n"
        "    Antonio entrants weighted by their own school\n"
        f"    ({n_stu:,} students). Recorded zero enrollment in core\n"
        "    science is rare at\n"
        f"    the sending schools ({min(core):g}--{max(core):g}\\% zero\n"
        "    enrollment), while calculus"
        f" ({adv['Calculus']:g}\\%), AP mathematics"
        f" ({adv['AP mathematics']:g}\\%), and AP science"
        f" ({adv['AP science']:g}\\%) show sizable provision deserts.\n"
        "    The measure is zero \\emph{enrollment}: a course offered but\n"
        "    taken by nobody counts as zero, and the upstream zero\n"
        "    coding is under audit (a recorded zero may mix true zero\n"
        "    enrollment with reserve-coded values;\n"
        "    Appendix~\\ref{app:science}), so the percentages read as\n"
        "    upper bounds on true zero enrollment.}\n"
        "  \\label{figScienceProvision}\n"
        "\\end{figure}\n",
        encoding="utf-8")
    return str(pdf)


if __name__ == "__main__":
    print(" ", figure())
