"""figSendingPoverty: child poverty of the sending districts.

Context exhibit of Appendix B. Compares two distributions of SAIPE child
poverty over Texas school districts: weighted by the students each
district sent to the institution, and weighted by the children each
district holds. Poverty is the district's mean SAIPE rate over vintages
2010--2018 (the high-school years of these students span that window).

Population: students active between Fall 2014 and Fall 2019 whose high
school resolves to a Texas public school district. The aggregates are
written by student_success/linkage_profile.py (histogram, ten largest
sending districts, medians and counts; no exported cell rests on fewer
than ten students). This program reads those files only (csv and json
modules and numpy, no student records, no database). Writes vector PDF,
300-DPI PNG, TeX snippet, and backing CSVs into figures/paper0.
"""
import csv
import json
import shutil
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

HERE = Path(__file__).resolve().parent
FIG_SRC = HERE.parent / "figures" / "student_success"
FIG_DIR = HERE.parent / "figures" / "paper0"

BLUE, GRAY = "#2a78d6", "#c3c2b7"
INK, INK_MUTED, GRID = "#0b0b0b", "#898781", "#e1e0d9"

plt.rcParams.update({"pdf.fonttype": 42, "font.family": "sans-serif",
                     "text.color": INK})


def figure() -> str:
    with open(FIG_SRC / "linkage_profile_stats.json", encoding="utf-8") as f:
        stats = json.load(f)["active"]
    sp, cov = stats["sending_poverty"], stats["coverage"]
    with open(FIG_SRC / "linkage_profile_poverty.csv", newline="",
              encoding="utf-8") as f:
        rows = list(csv.DictReader(f))

    lo = np.array([float(r["bin_low"]) for r in rows])
    hi = np.array([float(r["bin_high"]) for r in rows])
    h_kid = np.array([float(r["pct_texas_children"]) for r in rows])
    h_stu = np.array([float(r["pct_students"]) for r in rows])
    n_students, n_districts = sp["n_students"], sp["n_districts"]
    med_stu = sp["median_student_weighted"]
    med_kids = sp["median_child_weighted"]
    n_base = cov["n_texas_name"]
    centers = (lo + hi) / 2
    w = float(hi[0] - lo[0]) * 0.42

    fig, ax = plt.subplots(figsize=(13, 6.5))
    ax.bar(centers - w / 2, h_kid, w * 0.92, color=GRAY, zorder=3,
           label="all Texas children ages 5-17, by district")
    ax.bar(centers + w / 2, h_stu, w * 0.92, color=BLUE, zorder=3,
           label=f"UT San Antonio students (N={n_students:,}), "
                 "by sending district")
    for med, col in ((med_kids, INK_MUTED), (med_stu, BLUE)):
        ax.axvline(med, color=col, lw=1.6, ls="--", zorder=4)
    top = ax.get_ylim()[1]
    ax.text(med_kids + 0.5, top * 0.72, f"median {med_kids:.1f}%",
            fontsize=13, color=INK_MUTED, va="top", ha="left")
    ax.text(med_stu - 0.5, top * 0.62, f"median {med_stu:.1f}%",
            fontsize=13, color=BLUE, va="top", ha="right")
    ax.set_xlabel("district child poverty rate, mean of SAIPE 2010-2018 "
                  "vintages (%)", fontsize=17)
    ax.set_ylabel("share of group (%)", fontsize=17)
    ax.tick_params(labelsize=15, color=INK_MUTED)
    ax.grid(axis="y", color=GRID, linewidth=0.6, zorder=0)
    ax.set_axisbelow(True)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(INK_MUTED)
    ax.legend(loc="upper right", fontsize=13, frameon=False)
    fig.tight_layout()

    FIG_DIR.mkdir(parents=True, exist_ok=True)
    pdf = FIG_DIR / "figSendingPoverty.pdf"
    fig.savefig(pdf, bbox_inches="tight")
    fig.savefig(FIG_DIR / "figSendingPoverty.png", dpi=300,
                bbox_inches="tight")
    plt.close(fig)

    # backing files of the figure: the aggregates as drawn
    shutil.copyfile(FIG_SRC / "linkage_profile_poverty.csv",
                    FIG_DIR / "figSendingPoverty_data.csv")
    shutil.copyfile(FIG_SRC / "linkage_profile_districts.csv",
                    FIG_DIR / "figSendingPoverty_districts.csv")

    pooled = sp["n_bins_pooled"]
    pooled_note = (
        "    Bins with fewer than ten students are pooled into the\n"
        "    neighboring bin.\n" if pooled else "")
    (FIG_DIR / "figSendingPoverty.tex").write_text(
        "% Canonical caption for figSendingPoverty.pdf\n"
        "% Generated by: programs/paper0/sending_poverty.py from the\n"
        "% aggregates of programs/student_success/linkage_profile.py.\n"
        "% Regenerate: python programs/paper0/sending_poverty.py\n"
        "\\begin{figure}[tbp]\n"
        "  \\centering\n"
        "  \\includegraphics[width=\\textwidth]{figSendingPoverty.pdf}\n"
        "  \\caption{Child poverty of the sending districts. Gray: the\n"
        "    distribution of district child poverty (mean SAIPE rate,\n"
        "    2010--2018 vintages) over all Texas children aged 5--17,\n"
        "    weighting each district by the children it holds. Blue: the\n"
        f"    same distribution over the {n_students:,} students active\n"
        "    between Fall 2014 and Fall 2019 whose sending high school\n"
        "    resolves to a Texas public school district\n"
        f"    ({n_districts:,} districts), weighting each district by the\n"
        "    students it sent. Weights are aggregate counts; no\n"
        "    student-level record enters the exhibit. Dashed lines mark\n"
        "    the weighted medians.\n"
        + pooled_note +
        f"    The exhibit reaches {100 * n_students / n_base:.1f}\\% of\n"
        f"    the {n_base:,} students with a Texas high-school name. The\n"
        "    district poverty of the other students is unobserved, so\n"
        "    the blue distribution describes the matched students only.}\n"
        "  \\label{figSendingPoverty}\n"
        "\\end{figure}\n",
        encoding="utf-8")

    print(f"students={n_students:,} districts={n_districts:,} "
          f"median(student-weighted)={med_stu:.1f}% "
          f"median(child-weighted)={med_kids:.1f}%")
    return str(pdf)


if __name__ == "__main__":
    print(" ", figure())
