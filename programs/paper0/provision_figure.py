"""figProvisionBands: credit arrival by sending-school AP-math provision.

Context exhibit of Appendix B. For each band of sending-school
AP-mathematics provision (share of the school's students enrolled in AP
mathematics, CRDC 2017-18), the bars show the share of the students from
that band who arrived with AP credit and with dual-enrollment credit.

Population: students active between Fall 2014 and Fall 2019 whose high
school resolves to a school of the CRDC 2017-18 universe. The aggregates
are written by student_success/linkage_profile.py
(figures/student_success/linkage_profile_provision.csv; every cell holds
at least ten students). This program reads that file only (csv module and
numpy, no student records). Writes vector PDF, 300-DPI PNG, TeX snippet,
and backing CSV into figures/paper0.
"""
import csv
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

HERE = Path(__file__).resolve().parent
FIG_SRC = HERE.parent / "figures" / "student_success"
FIG_DIR = HERE.parent / "figures" / "paper0"

BLUE, ORANGE = "#2a78d6", "#eb6834"
INK, INK_MUTED, GRID = "#0b0b0b", "#898781", "#e1e0d9"

BAND_LABEL = {
    "0. offers no AP maths": "zero AP-math enrollment",
    "1. under 2%": "under 2%",
    "2. 2-5%": "2-5%",
    "3. over 5%": "over 5%",
}

plt.rcParams.update({"pdf.fonttype": 42, "font.family": "sans-serif",
                     "text.color": INK})


def figure() -> str:
    with open(FIG_SRC / "linkage_profile_provision.csv", newline="",
              encoding="utf-8") as f:
        rows = sorted(csv.DictReader(f), key=lambda r: r["ap_offer_band"])

    bands = [BAND_LABEL[r["ap_offer_band"]] for r in rows]
    ap = np.array([float(r["pct_ap"]) for r in rows])
    dual = np.array([float(r["pct_dual"]) for r in rows])
    n_stu = [int(r["n_students"]) for r in rows]
    n_sch = [int(r["n_schools"]) for r in rows]

    x = np.arange(len(bands))
    w = 0.36
    fig, ax = plt.subplots(figsize=(13, 6.2))
    ax.bar(x - w / 2, ap, w * 0.92, color=BLUE, zorder=3,
           label="arrived with AP mathematics credit")
    ax.bar(x + w / 2, dual, w * 0.92, color=ORANGE, zorder=3,
           label="arrived with dual-enrollment credit")
    for i in range(len(bands)):
        ax.text(x[i] - w / 2, ap[i] + 0.35, f"{ap[i]:.1f}", ha="center",
                fontsize=13, color=BLUE, fontweight="bold")
        ax.text(x[i] + w / 2, dual[i] + 0.35, f"{dual[i]:.1f}",
                ha="center", fontsize=13, color=ORANGE, fontweight="bold")
    labels = [f"{b}\n{s:,} schools · {n:,} students"
              for b, s, n in zip(bands, n_sch, n_stu)]
    ax.set_xticks(x)
    ax.set_xticklabels(labels, fontsize=12.5)
    ax.set_ylabel("share of students from the band (%)", fontsize=17)
    ax.tick_params(axis="y", labelsize=15, color=INK_MUTED)
    ax.tick_params(axis="x", color=INK_MUTED)
    ax.grid(axis="y", color=GRID, linewidth=0.6, zorder=0)
    ax.set_axisbelow(True)
    ax.set_ylim(0, max(28.0, 1.12 * float(max(ap.max(), dual.max()))))
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(INK_MUTED)
    ax.legend(loc="upper right", fontsize=13, frameon=False)
    fig.tight_layout()

    FIG_DIR.mkdir(parents=True, exist_ok=True)
    pdf = FIG_DIR / "figProvisionBands.pdf"
    fig.savefig(pdf, bbox_inches="tight")
    fig.savefig(FIG_DIR / "figProvisionBands.png", dpi=300,
                bbox_inches="tight")
    plt.close(fig)

    with open(FIG_DIR / "figProvisionBands_data.csv", "w", newline="",
              encoding="utf-8") as f:
        out = csv.writer(f)
        out.writerow(["band", "n_schools", "n_students", "pct_ap",
                      "pct_dual"])
        for i, r in enumerate(rows):
            out.writerow([r["ap_offer_band"], n_sch[i], n_stu[i], ap[i],
                          dual[i]])

    (FIG_DIR / "figProvisionBands.tex").write_text(
        "% Canonical caption for figProvisionBands.pdf\n"
        "% Generated by: programs/paper0/provision_figure.py from the\n"
        "% aggregates of programs/student_success/linkage_profile.py\n"
        "% (linkage_profile_provision.csv).\n"
        "% Regenerate: python programs/paper0/provision_figure.py\n"
        "\\begin{figure}[tbp]\n"
        "  \\centering\n"
        "  \\includegraphics[width=\\textwidth]{figProvisionBands.pdf}\n"
        "  \\caption{Credit arrival by sending-school AP-mathematics\n"
        "    provision, among students active between Fall 2014 and Fall\n"
        "    2019 whose high school is resolved. Sending schools are\n"
        "    banded by the share of their own students enrolled in AP\n"
        "    mathematics (CRDC 2017--18); bars show the share of the\n"
        "    students from each band who arrived with AP credit (blue)\n"
        "    and with dual-enrollment credit (orange); school and\n"
        f"    student counts under each band ({sum(n_sch):,} schools,\n"
        f"    {sum(n_stu):,} students in total). AP arrival rises from\n"
        f"    {ap[0]:.1f}\\% to {ap[-1]:.1f}\\% across the bands while\n"
        f"    dual-enrollment arrival falls from {dual[0]:.1f}\\% to\n"
        f"    {dual[-1]:.1f}\\%: the two arrival shares move in opposite\n"
        "    directions across the bands. Provision is zero recorded\n"
        "    \\emph{enrollment} in the cycle, described at the school\n"
        "    level; the exhibit profiles the sending-school context and\n"
        "    is never treated as a student exposure history. Every cell\n"
        "    holds at least ten students.}\n"
        "  \\label{figProvisionBands}\n"
        "\\end{figure}\n",
        encoding="utf-8")
    return str(pdf)


if __name__ == "__main__":
    print(" ", figure())
